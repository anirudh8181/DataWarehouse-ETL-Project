/*

A surrogate key is a unique key generated by the Data Warehouse itself, rather than 
coming from the source system.

In simple terms:

Surrogate key = artificial/internal ID created by the warehouse to uniquely identify a record.

Example:

Suppose your source CRM has:

customer_id | name   | city
------------|--------|--------
101         | Rahul  | Chennai
102         | Anirudh| Bangalore

Here customer_id is the source/business key.

When loading into the warehouse, you might create:

PM_KEY | customer_id | name    | city
-------|-------------|---------|--------
1      | 101         | Rahul   | Chennai
2      | 102         | Anirudh | Bangalore

Here:

customer_id → Natural/Business Key
PM_KEY → Surrogate Key

The warehouse generated 1 and 2; the source system didn't provide them.


Natural Key vs Surrogate Key

|              | Natural/Business Key      | Surrogate Key               |
| ------------ | ------------------------- | --------------------------- |
| Comes from   | Source system             | Data Warehouse              |
| Example      | `customer_id = 101`       | `PM_KEY = 1`                |
| Meaning      | Has business meaning      | Usually no business meaning |
| Generated by | Source                    | Warehouse/ETL               |
| Used for     | Identifying source record | Warehouse relationships     |




*/





/*

often we introduce a PM_KEY (primary/surrogate key) before or while loading a dimension table into the Data Warehouse, 
but it depends on the table and warehouse design.

For a typical dimension table, the flow is:

Source Customer Table
        ↓
   Extract
        ↓
   Staging/Bronze
        ↓
 Transform/Clean
        ↓
 Generate PM_KEY
        ↓
 Data Warehouse Dimension
 
Example:

Suppose the source has:

customer_id | name    | city
------------|---------|--------
101         | Rahul   | Chennai
102         | Anirudh | Bangalore

You might create the warehouse dimension as:

PM_KEY | customer_id | name    | city
-------|-------------|---------|----------
1      | 101         | Rahul   | Chennai
2      | 102         | Anirudh | Bangalore

Here:

customer_id → Business/Natural Key coming from the source.
PM_KEY → Surrogate key generated by the warehouse.
PM_KEY is typically the primary key of the dimension table.
Why introduce PM_KEY?

The main reason is that source-system IDs aren't always suitable as warehouse keys.

For example, you could have:

CRM:
customer_id = 101

ERP:
customer_id = 101

Those might represent different entities.
Also, source IDs can change, while the warehouse surrogate key can remain stable.

Very important: Facts use the PM_KEY

Suppose you have:

Dimension:

dim_customer

PM_KEY | customer_id | name
-------|-------------|-------
1      | 101         | Rahul
2      | 102         | Anirudh


Fact:

fact_sales

sales_id | customer_PM_KEY | amount
---------|------------------|-------
5001     | 1                | 10000
5002     | 2                | 15000

So the relationship becomes:

dim_customer
     │
     │ PM_KEY
     ↓
fact_sales

This is one of the important concepts behind a star schema.

One correction to your wording

Don't think:
"Every table must get a PM_KEY before entering the Data Warehouse."

Instead think:
Dimension tables commonly receive a surrogate/PM key, and fact tables store those dimension keys as foreign keys.

For example:

                  DATA WAREHOUSE

             ┌─────────────────┐
             │  dim_customer   │
             │-----------------│
             │ PM_KEY          │
             │ customer_id     │
             │ customer_name   │
             └────────┬────────┘
                      │
                      │ PM_KEY
                      ↓
             ┌─────────────────┐
             │   fact_sales    │
             │-----------------│
             │ sales_key       │
             │ customer_PM_KEY │
             │ product_PM_KEY  │
             │ date_PM_KEY     │
             │ sales_amount    │
             └─────────────────┘

If ETL project has Business Objects → Facts → Dimensions → Integration Model, 
then PM_KEY is particularly important because it is usually part of how the dimension and fact relationships are established.


*/

